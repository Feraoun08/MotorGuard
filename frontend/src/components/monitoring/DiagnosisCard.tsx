import { BrainCircuit, RefreshCw, AlertCircle } from "lucide-react";
import type { DiagnosisResponse } from "../../types/diagnosis";

interface DiagnosisCardProps {
  diagnosis: DiagnosisResponse | null;
  loading?: boolean;
  error?: string | null;
  onRefresh: () => void;
}

function formatConfidence(confidence: number) {
  const percentage =
    confidence <= 1
      ? confidence * 100
      : confidence;

  return `${percentage.toFixed(1)}%`;
}

export default function DiagnosisCard({
  diagnosis,
  loading = false,
  error,
  onRefresh,
}: DiagnosisCardProps) {
  return (
    <div className="diagnosis-card">
      <div className="diagnosis-header">
        <div className="diagnosis-heading">
          <span className="diagnosis-icon">
            <BrainCircuit size={22} />
          </span>

          <div>
            <h3>ML Diagnosis</h3>
            <p>Machine learning prediction</p>
          </div>
        </div>

        <button
          className="icon-button"
          onClick={onRefresh}
          disabled={loading}
          title="Refresh diagnosis"
        >
          <RefreshCw size={17} className={loading ? "spin" : ""} />
        </button>
      </div>

      {loading && !diagnosis ? (
        <div className="diagnosis-placeholder">
          Running model inference...
        </div>
      ) : error && !diagnosis ? (
        <div className="diagnosis-error">
          <AlertCircle size={18} />
          <span>{error}</span>
        </div>
      ) : diagnosis ? (
    <>
      <div className="diagnosis-result">
        <span className="diagnosis-result-label">
          Predicted class
        </span>

        <strong>{diagnosis.predicted_class}</strong>
      </div>

      <div className="diagnosis-confidence">
        <div className="diagnosis-confidence-header">
          <span>Confidence</span>
          <strong>{formatConfidence(diagnosis.confidence)}</strong>
        </div>

        <div className="confidence-track">
          <div
            className="confidence-fill"
            style={{
              width: `${Math.max(
                0,
                Math.min(
                  100,
                  diagnosis.confidence <= 1
                    ? diagnosis.confidence * 100
                    : diagnosis.confidence
                )
              )}%`,
            }}
          />
        </div>
      </div>

      <div className="diagnosis-metadata">
        <div>
          <span>Prediction timestamp</span>
          <strong>
            {new Date(diagnosis.timestamp).toLocaleString()}
          </strong>
        </div>

        {diagnosis.ground_truth && (
          <div>
            <span>Ground truth</span>
            <strong>{diagnosis.ground_truth}</strong>
          </div>
        )}
      </div>

      <div className="diagnosis-disclaimer">
        Prediction generated by the MotorGuard ML model. It is not
        a substitute for engineering inspection.
      </div>
    </>
      ) : (
        <div className="diagnosis-placeholder">
          No diagnosis available.
        </div>
      )}
    </div>
  );
}